# MAKES: src/dictionary.cone (the static dictionary of RFC 7932 Appendix A and its 121 word transforms from
# Appendix B) and src/contextluts.cone (the three context lookup tables of section 7.1), from the RFC's own text.
# RUN:   python brotlitables.py <rfc7932.txt>            (writes both files into src\ beside this script)
#        python brotlitables.py <rfc7932.txt> <google dictionary.bin>   (also checks the dictionary against it)
# Python's standard library only. The RFC text is fetched by the person running this
# (https://www.rfc-editor.org/rfc/rfc7932.txt); it is not kept in the repository. Change this script and run it,
# never the generated files.
#
# Every table is checked before it is written, against the lengths and CRC-32 values the RFC itself states:
#   the dictionary   122,784 bytes, CRC-32 0x5136cb04 (Appendix A)
#   the transforms   648 bytes of the serialization the RFC defines, CRC-32 0x3d965f81 (Appendix B)
#   Lut0, Lut1, Lut2 256 bytes each, CRC-32 0x8e91efb7, 0xd01a32f4, 0x0dd7a0d6 (section 7.1)
# and the dictionary's size against NDBITS (the sum of length << NDBITS[length] over 4..24). The compiled data is
# checked by the test stream tests/data/own/dictwords.br, which names a word of every length with every transform
# and must decompress to bytes made from the RFC's text.
import ast, os, re, sys, zlib

DICT_LEN, DICT_CRC = 122784, 0x5136CB04
TRANS_LEN, TRANS_CRC = 648, 0x3D965F81
LUT_CRC = {0: 0x8E91EFB7, 1: 0xD01A32F4, 2: 0x0DD7A0D6}
KINDS = ["Identity", "FermentFirst", "FermentAll"] + ["OmitFirst%d" % i for i in range(1, 10)] + ["OmitLast%d" % i for i in range(1, 10)]


def fail(msg):
    sys.exit("brotlitables: " + msg)


def crc32(b):
    return zlib.crc32(b) & 0xFFFFFFFF


def dictionary(lines):
    start = next(i for i, l in enumerate(lines) if l.startswith("Appendix A."))
    end = next(i for i, l in enumerate(lines) if l.strip().startswith("NDBITS :="))
    hexs = "".join(l.strip() for l in lines[start:end] if re.fullmatch(r"\s+[0-9a-f]{2,}", l) and len(l.strip()) % 2 == 0)
    data = bytes.fromhex(hexs)
    nd = "".join(lines[end:end + 4])
    ndbits = [int(x) for x in re.findall(r"\d+", nd.split(":=")[1].split("Appendix")[0])][:25]
    if len(ndbits) != 25:
        fail("NDBITS has %d entries" % len(ndbits))
    if len(data) != DICT_LEN:
        fail("dictionary is %d bytes, the RFC says %d" % (len(data), DICT_LEN))
    if crc32(data) != DICT_CRC:
        fail("dictionary CRC-32 is %08x, the RFC says %08x" % (crc32(data), DICT_CRC))
    if sum(n << ndbits[n] for n in range(4, 25)) != DICT_LEN:
        fail("NDBITS does not add up to the dictionary's size")
    return data, ndbits


def transforms(lines):
    start = next(i for i, l in enumerate(lines) if l.startswith("Appendix B."))
    end = next(i for i, l in enumerate(lines) if l.startswith("Appendix C."))
    row = re.compile(r'^\s+(\d+)\s+("(?:[^"\\]|\\.)*")\s+(\w+)\s+("(?:[^"\\]|\\.)*")\s*$')
    out = {}
    for l in lines[start:end]:
        m = row.match(l)
        if m:
            def cstr(s):
                return ast.literal_eval(s).encode("latin-1")   # C escapes \xNN, \", \n: each is a byte
            out[int(m.group(1))] = (cstr(m.group(2)), KINDS.index(m.group(3)), cstr(m.group(4)))
    if sorted(out) != list(range(121)):
        fail("found transforms %d, expected ids 0..120" % len(out))
    ser = b"".join(p + b"\0" + bytes([k]) + s + b"\0" for p, k, s in (out[i] for i in range(121)))
    if len(ser) != TRANS_LEN or crc32(ser) != TRANS_CRC:
        fail("transforms: %d bytes, CRC-32 %08x; the RFC says %d and %08x" % (len(ser), crc32(ser), TRANS_LEN, TRANS_CRC))
    return [out[i] for i in range(121)]


def luts(lines):
    res = []
    for n in range(3):
        i = next(i for i, l in enumerate(lines) if l.strip() == "Lut%d :=" % n)
        vals = []
        j = i + 1
        while len(vals) < 256:
            if re.fullmatch(r"\s+[0-9, ]+", lines[j]):
                vals += [int(x) for x in re.findall(r"\d+", lines[j])]
            j += 1
        if len(vals) != 256 or crc32(bytes(vals)) != LUT_CRC[n]:
            fail("Lut%d does not match the RFC's CRC-32" % n)
        res.append(vals)
    return res


def lit(b):
    s = []
    for c in b:
        ch = chr(c)
        s.append(ch if (32 <= c < 127 and ch not in '"\\{}') else "\\x%02X" % c)
    return "".join(s)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    lines = open(sys.argv[1], encoding="ascii", errors="replace").read().split("\n")
    data, ndbits = dictionary(lines)
    if len(sys.argv) > 2 and open(sys.argv[2], "rb").read() != data:
        fail("the dictionary differs from " + sys.argv[2])
    trans = transforms(lines)
    lut = luts(lines)
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src")

    L = ["// GENERATED by packages/brotli/brotlitables.py from RFC 7932 Appendices A and B: do not edit by hand.",
         "// The static dictionary (%d bytes, CRC-32 0x%08x as the RFC states), one string per word length,"
         % (DICT_LEN, DICT_CRC),
         "// and the 121 word transforms. The RFC text carries the IETF Trust's notice; the dictionary is also in",
         "// Google's brotli repository under the MIT licence.", "",
         "// Words of length n: 1 << dictBits[n]; the words of length n are dictNN, n bytes each, in order",
         "let dictBits: Array[u8, 25] = [" + ", ".join("%du8" % b for b in ndbits) + "];", ""]
    off = 0
    for n in range(4, 25):
        size = n << ndbits[n]
        L.append('const dict%d = "%s";' % (n, lit(data[off:off + size])))
        off += size
    L.append("")
    # The transforms' prefix and suffix strings go in one text, each at an offset, with its length
    text = b""
    at = {}

    def put(b):
        nonlocal text
        if b not in at:
            at[b] = len(text)
            text += b
        return at[b]
    pre = [(put(p), len(p)) for p, k, s in trans]
    suf = [(put(s), len(s)) for p, k, s in trans]
    L.append("// The prefix and suffix strings of the transforms")
    L.append('const transformText = "%s";' % lit(text))
    L.append("// Transform i is: prefix (offset, length) in transformText, the elementary kind, suffix (offset, length)")
    L.append("// Kinds: 0 Identity, 1 FermentFirst, 2 FermentAll, 3 to 11 OmitFirst1 to OmitFirst9, 12 to 20 OmitLast1 to OmitLast9")

    def arr(name, ty, vals):
        L.append("let %s: Array[%s, 121] = [%s];" % (name, ty, ", ".join("%d%s" % (v, ty) for v in vals)))
    arr("transformPrefixOff", "u16", [a for a, b in pre])
    arr("transformPrefixLen", "u8", [b for a, b in pre])
    arr("transformKind", "u8", [k for p, k, s in trans])
    arr("transformSuffixOff", "u16", [a for a, b in suf])
    arr("transformSuffixLen", "u8", [b for a, b in suf])
    L.append("")
    with open(os.path.join(here, "dictionary.cone"), "w", newline="\n") as f:
        f.write("\n".join(L))

    L = ["// GENERATED by packages/brotli/brotlitables.py from RFC 7932 section 7.1: do not edit by hand.",
         "// The context lookup tables Lut0, Lut1 and Lut2 (256 bytes each; CRC-32 0x8e91efb7, 0xd01a32f4,",
         "// 0x0dd7a0d6 as the RFC states, checked by the generator and by the tests).", ""]
    for n in range(3):
        L.append("let lut%d: Array[u8, 256] = [" % n)
        for i in range(0, 256, 16):
            L.append("  " + ", ".join("%du8" % v for v in lut[n][i:i + 16]) + ("," if i < 240 else ""))
        L.append("];")
        L.append("")
    with open(os.path.join(here, "contextluts.cone"), "w", newline="\n") as f:
        f.write("\n".join(L))
    print("wrote dictionary.cone and contextluts.cone; all CRC-32 checks passed")


if __name__ == "__main__":
    main()
