"""Check the declarations in ../src/*.cone against LLVM-C's own headers.

    python check_headers.py [<llvm include folder>]        (default C:/LLVM/23/include, or /usr/lib/llvm-23/include)

For every `fn Name(...)` in an extern block of src/*.cone the header must declare LLVMName with the same
number of parameters, each of the Cone type its C type maps to (the rules are in map_type below, written
from llvmc.cone's header: a handle LLVMXxxRef is *Xxx, LLVMBool is i32, `unsigned` is u32, a C enum
taken as an argument is the Cone enum of the same name, a `const char *` is a cstr or a *u8, ...), and the
same result. Every Cone enum and constant is compared with the value the header gives its enumerator
(the header's expressions are evaluated here). It prints each disagreement and exits 1 if there are any.
It does not run LLVM; tests/symbols.cone is what proves the symbols exist.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")


def include_folder():
    if len(sys.argv) > 1:
        return sys.argv[1]
    for candidate in ("C:/LLVM/23/include", "/usr/lib/llvm-23/include"):
        if os.path.isdir(candidate):
            return candidate
    sys.exit("no LLVM include folder: pass llvm-c's parent folder")


def blank_comments(text):
    text = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"(?m)^\s*#[^\n]*", "", text)


def read_headers(include):
    funcs, enums = {}, {}
    folder = os.path.join(include, "llvm-c")
    for path in glob.glob(folder + "/*.h") + glob.glob(folder + "/Transforms/*.h"):
        text = blank_comments(open(path, encoding="utf-8", errors="replace").read())
        for m in re.finditer(r"LLVM_C_ABI\s+([^;{}]*?)\b(LLVM\w+)\s*\(([^;{}]*?)\)\s*;", text, flags=re.S):
            funcs[m.group(2)] = (" ".join(m.group(1).split()), " ".join(m.group(3).split()))
        # the checked casts and the per-target initialisers are generated by macros
        for m in re.finditer(r"macro\((\w+)\)", text):
            funcs["LLVMIsA" + m.group(1)] = ("LLVMValueRef", "LLVMValueRef Val")
        for m in re.finditer(r"typedef\s+enum\s*\w*\s*\{(.*?)\}\s*(LLVM\w+)\s*;", text, flags=re.S):
            enums[m.group(2)] = parse_enum(m.group(1))
        for m in re.finditer(r"(?m)^enum\s*\{(.*?)\}\s*;", text, flags=re.S):
            for k, v in parse_enum(m.group(1)).items():
                enums.setdefault("<anonymous>", {})[k] = v
    for target in ("X86", "WebAssembly", "SPIRV"):
        for part in ("TargetInfo", "Target", "TargetMC", "AsmPrinter", "AsmParser"):
            funcs.setdefault("LLVMInitialize" + target + part, ("void", "void"))
    return funcs, enums


def parse_enum(body):
    values, names, nxt = {}, {}, 0
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        name, _, expr = item.partition("=")
        name = name.strip()
        if expr.strip():
            expr = re.sub(r"\b(\d+)[uU]\b", r"\1", " ".join(expr.split()))
            try:
                nxt = int(eval(expr, {"__builtins__": {}}, dict(names)))  # the header's own constant expression
            except Exception:
                continue  # an enumerator of an enum this package does not declare, built from names not read here
        names[name] = nxt
        values[name] = nxt
        nxt += 1
    return values


def map_type(c, ret=False):
    """The Cone types a C type may be declared as."""
    c = " ".join(c.replace("*", " * ").split()).replace("* *", "**").replace(" *", "*")
    c = c.replace("const ", "").strip()
    if c == "void":
        return {""}
    if c in ("LLVMBool", "int"):
        return {"i32"}
    if c in ("unsigned", "unsigned int", "LLVMAttributeIndex", "LLVMDIFlags", "LLVMMetadataKind", "LLVMDWARFTypeEncoding"):
        return {"u32"}
    if c in ("unsigned long long", "uint64_t"):
        return {"u64"}
    if c == "size_t":
        return {"usize"}
    if c == "double":
        return {"f64"}
    if c == "char*":
        return {"*u8"}
    if c == "char**":
        return {"**u8"}
    if c in ("char*const*", "char*const *"):
        return {"**u8"}
    if c == "unsigned*":
        return {"*u32"}
    if c == "size_t*":
        return {"*usize"}
    if c == "LLVMErrorTypeId":
        return {"*u8"}
    if c == "LLVMFatalErrorHandler":
        return {"&fn @c"}
    if c == "LLVMValueMetadataEntry*":
        return {"*ValueMetadataEntry"}
    m = re.fullmatch(r"LLVM(\w+)Ref(\**)", c)
    if m:
        return {m.group(2) + "*" + m.group(1)}
    if re.fullmatch(r"LLVM\w+", c):
        return {c[4:]}
    return {"?" + c}


def read_cone():
    funcs, enums, consts, structs = {}, {}, {}, set()
    for path in sorted(glob.glob(SRC + "/*.cone")):
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r"^  fn (\w+)\((.*?)\)\s*([^;{)]*);", text, flags=re.S | re.M):
            params = [p.strip() for p in re.split(r",(?![^()]*\))", m.group(2)) if p.strip()]
            funcs[m.group(1)] = ([p.split(":", 1)[1].strip() if ":" in p else p for p in params], m.group(3).strip(),
                                 os.path.basename(path))
        for m in re.finditer(r"pub enum (\w+): u32 \{(.*?)\}", text, flags=re.S):
            enums[m.group(1)] = {k: int(v) for k, v in re.findall(r"(\w+) = (\d+)", m.group(2))}
        for m in re.finditer(r"^pub const (\w+) = (\d+)u32;", text, flags=re.M):
            consts[m.group(1)] = int(m.group(2))
        for m in re.finditer(r"pub struct @opaque (\w+) \{\}", text):
            structs.add(m.group(1))
    return funcs, enums, consts, structs


def split_c_params(args):
    if args.strip() in ("", "void"):
        return []
    out = []
    for a in args.split(","):
        a = " ".join(a.replace("unsigned long long", "ULL_").replace("unsigned int", "UINT_").split())
        a = re.sub(r"\bunsigned\b", "UINT_", a)
        m = re.match(r"^(.*?)([A-Za-z_]\w*)$", a)
        if m and m.group(1).replace("const", "").strip():
            a = m.group(1).strip()
        out.append(a.replace("ULL_", "unsigned long long").replace("UINT_", "unsigned"))
    return out


def main():
    include = include_folder()
    cfuncs, cenums = read_headers(include)
    funcs, enums, consts, structs = read_cone()
    problems = []

    for name, (params, ret, where) in sorted(funcs.items()):
        c = cfuncs.get("LLVM" + name)
        if c is None:
            problems.append("%s (%s): the header declares no LLVM%s" % (name, where, name))
            continue
        cret, cargs = c
        cparams = split_c_params(cargs)
        if len(cparams) != len(params):
            problems.append("%s: %d parameters, the header has %d" % (name, len(params), len(cparams)))
            continue
        for i, (cp, p) in enumerate(zip(cparams, params)):
            want = map_type(cp)
            # const char * is a cstr, or a *u8 where a length follows or LLVM allows a null
            if "char*" in cp.replace(" ", "") and cp.replace(" ", "").startswith("constchar*") and not cp.endswith("**"):
                want = {"cstr", "*u8"}
            if cp.replace(" ", "") == "constchar*const*":
                want = {"**u8"}
            if not any(p == w or (w.startswith("&fn") and p.startswith("&fn")) for w in want):
                if re.fullmatch(r"LLVM\w+", cp) and p == "u32" and cp[4:] in ("DIFlags", "CallConv"):
                    continue
                problems.append("%s parameter %d: Cone has %s, the C type %s needs %s" % (name, i + 1, p, cp, sorted(want)))
        want = map_type(cret, True)
        if cret.replace(" ", "") == "constchar*":
            want = {"*u8", "cstr"}
        if ret not in want and not (cret in ("LLVMDIFlags",) and ret == "u32"):
            problems.append("%s result: Cone has %r, the C type %s needs %s" % (name, ret, cret, sorted(want)))

    # every handle type named exists
    for name, (params, ret, where) in funcs.items():
        for t in params + [ret]:
            base = t.lstrip("*")
            if t.startswith("*") and base[:1].isupper() and base not in structs and base not in ("ErrorRef",) and base not in structs:
                problems.append("%s: the type %s is declared by no @opaque struct" % (name, base))

    # enums and constants
    for ename, values in sorted(enums.items()):
        c = cenums.get("LLVM" + ename)
        if c is None:
            problems.append("enum %s: no LLVM%s in the headers" % (ename, ename))
            continue
        for k, v in values.items():
            if c.get("LLVM" + k) != v:
                problems.append("enum %s: %s = %d, the header has %s" % (ename, k, v, c.get("LLVM" + k)))
        if set("LLVM" + k for k in values) != set(c):
            problems.append("enum %s: variants differ from the header's: %s" % (ename, sorted(set(c) ^ set("LLVM" + k for k in values))))
    allc = {}
    for e in cenums.values():
        allc.update(e)
    for k, v in sorted(consts.items()):
        if k in ("AttributeReturnIndex", "AttributeFunctionIndex"):
            expect = {"AttributeReturnIndex": 0, "AttributeFunctionIndex": 0xFFFFFFFF}[k]
            if v != expect:
                problems.append("const %s = %d, expected %d" % (k, v, expect))
        elif allc.get("LLVM" + k) != v:
            problems.append("const %s = %d, the header has %s" % (k, v, allc.get("LLVM" + k)))

    print("%d declarations, %d enums (%d variants), %d constants checked against %s: %d problems" % (
        len(funcs), len(enums), sum(len(v) for v in enums.values()), len(consts), include, len(problems)))
    for p in problems:
        print("  " + p)
    sys.exit(1 if problems else 0)


main()
