"""Make packages/zonedata/src/windowszones.cone from CLDR's windowsZones.xml.

The table is the territory "001" row of each Windows zone id in
common/supplemental/windowsZones.xml: the main IANA name of that Windows zone.
The file is fetched from a tagged CLDR release, never from main, so the table is
reproducible. The tag is the second argument (it goes into the generated file's
header):

    mkdir <new empty scratch dir outside the repo>
    curl -L -o <scratch>/windowsZones.xml \
        https://raw.githubusercontent.com/unicode-org/cldr/release-49/common/supplemental/windowsZones.xml
    python -I tools/zonedata/genwindowszones.py <scratch>/windowsZones.xml release-49

The XML is untrusted data: it is parsed with the standard library's ElementTree
(which does not fetch external entities) and every id and name is checked
against a plain character set before it reaches the Cone source.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "packages", "zonedata", "src", "windowszones.cone")

ID_OK = re.compile(r"^[A-Za-z0-9 .()+\-]+$")
NAME_OK = re.compile(r"^[A-Za-z0-9_+\-]+(/[A-Za-z0-9_+\-]+)*$")
TAG_OK = re.compile(r"^[A-Za-z0-9._\-]+$")


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: genwindowszones.py <windowsZones.xml> <CLDR release tag>")
    xml_path, tag = sys.argv[1], sys.argv[2]
    if not TAG_OK.match(tag):
        sys.exit("odd tag: " + tag)
    rows = {}
    for z in ET.parse(xml_path).getroot().iter("mapZone"):
        if z.get("territory") != "001":
            continue
        wid, iana = z.get("other"), z.get("type")
        if not ID_OK.match(wid) or not NAME_OK.match(iana):
            sys.exit("unexpected characters in %r -> %r" % (wid, iana))
        if wid in rows:
            sys.exit("two 001 rows for " + wid)
        rows[wid] = iana
    lines = [
        "// GENERATED by tools/zonedata/genwindowszones.py: do not edit by hand.",
        "// Source: CLDR common/supplemental/windowsZones.xml, release tag " + tag + ",",
        "// territory \"001\" rows (%d Windows zone ids)." % len(rows),
        "// https://github.com/unicode-org/cldr/blob/" + tag + "/common/supplemental/windowsZones.xml",
        "",
        "// The IANA name a Windows zone id stands for ('Eastern Standard Time' is",
        "// 'America/New_York'), or None for an id not in the table. The table is the",
        "// main IANA name of each of Windows' zones (CLDR's windowsZones, territory 001)",
        "pub fn windowsToIana(id: &str) Option[&'static str] {",
    ]
    for wid in sorted(rows):
        lines.append('  if id == "%s" { return Some[&str]("%s"); }' % (wid, rows[wid]))
    lines += ["  None", "}", ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %d ids to %s" % (len(rows), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
