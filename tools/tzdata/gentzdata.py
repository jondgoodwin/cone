#!/usr/bin/env python3
"""Generate packages/tzdata/src/tzdata.cone from an IANA tz release.

A bump when IANA releases is one run of this tool and one PR.

  1. Get tzdata<version>.tar.gz from https://data.iana.org/time-zones/releases/
     and unpack it into a folder of its own (the files are data; nothing in them runs).
  2. Compile it to TZif files with zic, which is a Linux tool (glibc ships it as
     /usr/sbin/zic). Slim files, which calendar reads after their last listed
     transition through the footer rule:
         zic -b slim -d out africa antarctica asia australasia backward etcetera \\
             europe factory northamerica southamerica
  3. Run this tool over the compiled folder:
         python tools/tzdata/gentzdata.py --zoneinfo out --version 2026f
     or, for a smaller package, with chrono-tz's zone filter (a regular expression
     searched in each zone name, so anchor it yourself):
         python tools/tzdata/gentzdata.py --zoneinfo out --version 2026f \\
             --filter '^(Europe/(London|Paris|Kyiv)|America/New_York|UTC)$'

Names that hold the same bytes (zic links) share one constant in the output.
The run prints the zone count, unique file count and sizes.
"""
import argparse, hashlib, os, re, sys


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--zoneinfo", required=True, help="folder of compiled TZif files (zic -d)")
    ap.add_argument("--version", required=True, help="IANA release, e.g. 2026f")
    ap.add_argument("--filter", default=None, help="regex searched in each zone name; only matches are kept")
    ap.add_argument("--out", default=None, help="output file (default: packages/tzdata/src/tzdata.cone in this repo)")
    a = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    out = a.out or os.path.join(here, "..", "..", "packages", "tzdata", "src", "tzdata.cone")
    rx = re.compile(a.filter) if a.filter else None

    zones = {}
    for root, _, files in os.walk(a.zoneinfo):
        for f in files:
            p = os.path.join(root, f)
            name = os.path.relpath(p, a.zoneinfo).replace(os.sep, "/")
            with open(p, "rb") as fh:
                data = fh.read()
            if data[:5] not in (b"TZif2", b"TZif3", b"TZif4"):
                continue            # not a version 2+ TZif file (calendar refuses version 1)
            if rx and not rx.search(name):
                continue
            zones[name] = data
    if not zones:
        sys.exit("no zones kept")

    unique = {}                      # digest -> (index, bytes)
    for n in sorted(zones):
        d = hashlib.sha256(zones[n]).hexdigest()
        if d not in unique:
            unique[d] = (len(unique), zones[n])

    def lit(b):
        s = []
        for c in b:
            ch = chr(c)
            s.append(ch if (ch.isascii() and ch.isalnum()) else "\\x%02X" % c)
        return "".join(s)

    L = []
    L.append("// GENERATED by tools/tzdata/gentzdata.py: do not edit by hand.")
    L.append("// Source: IANA tz database release %s (public domain), compiled with zic -b slim." % a.version)
    L.append("// https://data.iana.org/time-zones/releases/tzdata%s.tar.gz" % a.version)
    L.append("// Zones: %d names, %d distinct files%s." % (len(zones), len(unique),
             ", filtered by /%s/" % a.filter if a.filter else ", unfiltered"))
    L.append("")
    L.append("mod tzdata;")
    L.append("")
    L.append("// The IANA release the data comes from")
    L.append('pub const version = "%s";' % a.version)
    L.append("")
    for d, (i, b) in sorted(unique.items(), key=lambda kv: kv[1][0]):
        L.append('const z%d = "%s";' % (i, lit(b)))
    L.append("")
    L.append("// The TZif bytes of an IANA zone name, or None if the package holds no such zone.")
    L.append("// Feed them to calendar's Zone.fromTzif")
    L.append("pub fn find(name: &str) Option[&'static str] {")
    for n in sorted(zones):
        i = unique[hashlib.sha256(zones[n]).hexdigest()][0]
        L.append('  if name == "%s" { return Some[&str](z%d); }' % (n, i))
    L.append("  None")
    L.append("}")
    L.append("")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    text = "\n".join(L)
    with open(out, "w", newline="\n") as fh:
        fh.write(text)
    raw = sum(len(b) for _, b in unique.values())
    print("zones %d, distinct files %d, TZif bytes embedded %d, source file %d bytes" % (len(zones), len(unique), raw, len(text)))


main()
